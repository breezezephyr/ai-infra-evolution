def items():
    out = []
    for id_, topic, q, a, near in ROWS:
        out.append({"id": id_, "topic": topic, "q": q, "a": a, "near": near or None})
    return out

def validate(rows):
    ids = [r["id"] for r in rows]
    assert len(rows) == 100, len(rows)
    assert len(set(ids)) == 100
    assert len(set(r["q"] for r in rows)) == 100
    by = {r["id"]: r for r in rows}
    adv = [r for r in rows if r["near"]]
    assert len(adv) == 20, len(adv)
    for r in adv:
        assert r["near"] in by and r["near"] != r["id"]
        assert by[r["near"]]["a"] != r["a"]
    topics = collections.Counter(r["topic"] for r in rows)
    assert set(topics) and all(n == 10 for n in topics.values()), topics
    return topics

def main():
    rows = items()
    topics = validate(rows)
    path = os.path.join(HERE, "faq_seed.jsonl")
    with open(path, "w") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(path, len(rows), "adv", sum(1 for r in rows if r["near"]), dict(topics))

if __name__ == "__main__":
    main()
